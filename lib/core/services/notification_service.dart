  /// Helper to safely mask tokens in production logs (e.g. abcd1234...xyz789)
  static String _maskToken(String? token) {
    if (token == null || token.isEmpty) return 'none';
    if (token.length <= 16) return '***';
    return '${token.substring(0, 8)}...${token.substring(token.length - 6)}';
  }

  /// Identifies whether the incoming push is an account creation / welcome event
  static bool _isWelcomeNotification(RemoteMessage message) {
    final type = message.data['type']?.toString().toUpperCase();
    if (type == 'WELCOME' || type == 'CUSTOMER_WELCOME') return true;
    final title = (message.notification?.title ?? message.data['title'] ?? '')
        .toString();
    final body = (message.notification?.body ??
            message.data['body'] ??
            message.data['message'] ??
            '')
        .toString();
    if (title.contains('Welcome to QuikBoom') ||
        body.contains('account has been created successfully')) {
      return true;
    }
    return false;
  }

  /// Checks whether a welcome notification has already been displayed to this customer/device
  static Future<bool> _isWelcomeAlreadyShown(RemoteMessage message) async {
    if (!_isWelcomeNotification(message)) return false;

    final customerId =
        message.data['customerId']?.toString().trim().isNotEmpty == true
            ? message.data['customerId'].toString().trim()
            : 'default';
    final key = 'WELCOME_$customerId';

    if (_inMemoryShownWelcomeKeys.contains(key)) {
      return true;
    }

    try {
      final prefs = await SharedPreferences.getInstance();
      if (prefs.getBool('$_welcomeShownPrefPrefix$customerId') == true) {
        _inMemoryShownWelcomeKeys.add(key);
        return true;
      }
    } catch (_) {}

    return false;
  }

  /// Persistently marks the welcome notification as shown on this device
  static Future<void> _markWelcomeAsShown(RemoteMessage message) async {
    if (!_isWelcomeNotification(message)) return;
    final customerId =
        message.data['customerId']?.toString().trim().isNotEmpty == true
            ? message.data['customerId'].toString().trim()
            : 'default';
    final key = 'WELCOME_$customerId';
    _inMemoryShownWelcomeKeys.add(key);
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setBool('$_welcomeShownPrefPrefix$customerId', true);
    } catch (_) {}
  }

  /// Identifies whether the incoming push is a plan purchase success event
  static bool _isPlanPurchaseNotification(RemoteMessage message) {
    final type = (message.data['type'] ?? message.data['notificationType'])
        ?.toString()
        .toUpperCase();
    if (type == 'PLAN_PURCHASE_SUCCESS') return true;
    final title = (message.notification?.title ?? message.data['title'] ?? '')
        .toString();
    if (title.toLowerCase().contains('plan purchase successful') ||
        title.toLowerCase().contains('plan purchased')) {
      return true;
    }
    return false;
  }

  /// Derives a unique deduplication key for a plan purchase event
  static String _planPurchaseKey(RemoteMessage message) {
    final subId = message.data['subscriptionId']?.toString().trim();
    if (subId != null && subId.isNotEmpty) {
      return 'PLAN_SUB_$subId';
    }
    final notifId = message.data['notificationId']?.toString().trim();
    if (notifId != null && notifId.isNotEmpty) {
      return 'PLAN_NOTIF_$notifId';
    }
    final paymentId = message.data['paymentId']?.toString().trim();
    if (paymentId != null && paymentId.isNotEmpty) {
      return 'PLAN_PAY_$paymentId';
    }
    final customerId = message.data['customerId']?.toString().trim() ?? 'cust';
    final planId = message.data['planId']?.toString().trim() ?? 'plan';
    return 'PLAN_${customerId}_$planId';
  }

  /// Checks whether a plan purchase notification has already been displayed on this device
  static Future<bool> _isPlanPurchaseAlreadyShown(RemoteMessage message) async {
    if (!_isPlanPurchaseNotification(message)) return false;

    final key = _planPurchaseKey(message);
    if (_inMemoryShownPlanPurchaseKeys.contains(key)) {
      return true;
    }

    try {
      final prefs = await SharedPreferences.getInstance();
      if (prefs.getBool('$_planPurchaseShownPrefPrefix$key') == true) {
        _inMemoryShownPlanPurchaseKeys.add(key);
        return true;
      }
    } catch (_) {}

    return false;
  }

  /// Persistently marks the plan purchase notification as shown on this device
  static Future<void> _markPlanPurchaseAsShown(RemoteMessage message) async {
    if (!_isPlanPurchaseNotification(message)) return;
    final key = _planPurchaseKey(message);
    _inMemoryShownPlanPurchaseKeys.add(key);
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setBool('$_planPurchaseShownPrefPrefix$key', true);
    } catch (_) {}
  }

  @pragma('vm:entry-point')
  static Future<void> backgroundHandler(RemoteMessage message) async {
    debugPrint('[FCM] background message received');
    try {
      WidgetsFlutterBinding.ensureInitialized();
      DartPluginRegistrant.ensureInitialized();
      if (Firebase.apps.isEmpty) {
        await Firebase.initializeApp(
          options: DefaultFirebaseOptions.currentPlatform,
        );
      }

      final imageUrl = _extractImageUrl(message);
      final fcmDisplayedSystemTray = message.notification != null;
      final hasText =
          (message.notification?.title ?? message.data['title'] ?? '')
              .toString()
              .trim()
              .isNotEmpty ||
          (message.notification?.body ??
                  message.data['body'] ??
                  message.data['message'] ??
                  '')
              .toString()
              .trim()
              .isNotEmpty;

      // FCM already posted title/body when a notification payload is present.
      // Still show a local Big Picture notification when an image URL exists;
      // skip a duplicate text-only tray item when there is no image.
      if (fcmDisplayedSystemTray && imageUrl == null) return;
      if (!hasText && imageUrl == null) return;

      if (await _isWelcomeAlreadyShown(message)) {
        debugPrint(
          '[FCM] Welcome notification already displayed on this device. Skipping duplicate background tray item.',
        );
        return;
      }

      if (await _isPlanPurchaseAlreadyShown(message)) {
        debugPrint(
          '[FCM] Plan purchase notification already displayed on this device. Skipping duplicate background tray item.',
        );
        return;
      }

      final local = FlutterLocalNotificationsPlugin();
      const androidSettings = AndroidInitializationSettings(
        '@drawable/ic_notification',
      );
      const settings = InitializationSettings(android: androidSettings);
      await local.initialize(settings);

      final androidPlugin = local
          .resolvePlatformSpecificImplementation<
            AndroidFlutterLocalNotificationsPlugin
          >();
      await androidPlugin?.createNotificationChannel(_androidChannel);
      await androidPlugin?.createNotificationChannel(_legacyChannel);

      await _showAndroidLocalFromRemoteMessage(message, local);
      await _markWelcomeAsShown(message);
      await _markPlanPurchaseAsShown(message);
    } catch (e) {
      debugPrint('[FCM] backgroundHandler error: $e');
    }
  }

  static String? _extractImageUrl(RemoteMessage message) {
    final candidates = <dynamic>[
      message.data['imageUrl'],
      message.data['image_url'],
      message.data['image'],
      message.notification?.android?.imageUrl,
      message.notification?.apple?.imageUrl,
    ];
    for (final candidate in candidates) {
      final value = candidate?.toString().trim() ?? '';
      if (value.startsWith('http://') || value.startsWith('https://')) {
        return value;
      }
    }
    return null;
  }

  static int _localNotificationId(RemoteMessage message) {
    if (_isWelcomeNotification(message)) {
      final customerId =
          message.data['customerId']?.toString().trim().isNotEmpty == true
              ? message.data['customerId'].toString().trim()
              : 'customer';
      return ('WELCOME_CUSTOMER_$customerId').hashCode.abs() % 2147483647;
    }

    if (_isPlanPurchaseNotification(message)) {
      final key = _planPurchaseKey(message);
      return key.hashCode.abs() % 2147483647;
    }

    final notifId = message.data['notificationId']?.toString();
    if (notifId != null && notifId.isNotEmpty) {
      final parsed = int.tryParse(notifId);
      if (parsed != null && parsed > 0) {
        return parsed % 2147483647;
      }
      return 'NOTIFICATION_$notifId'.hashCode.abs() % 2147483647;
    }

    final title = message.notification?.title ?? message.data['title'] ?? '';
    final body = message.notification?.body ?? message.data['body'] ?? '';
    final fallback = '$title|$body';
    if (fallback.isNotEmpty) {
      return fallback.hashCode.abs() % 2147483647;
    }
    return 100001;
  }

  static bool _isDecodableNotificationImage(List<int> bytes) {
    if (bytes.length < 24 || bytes.length > 8 * 1024 * 1024) return false;
    if (bytes.length >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8) {
      return true; // JPEG
    }
    if (bytes.length >= 8 &&
        bytes[0] == 0x89 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x4E &&
        bytes[3] == 0x47) {
      return true; // PNG
    }
    if (bytes.length >= 12 &&
        bytes[0] == 0x52 &&
        bytes[1] == 0x49 &&
        bytes[2] == 0x46 &&
        bytes[3] == 0x46 &&
        bytes[8] == 0x57 &&
        bytes[9] == 0x45 &&
        bytes[10] == 0x42 &&
        bytes[11] == 0x50) {
      return true; // WEBP
    }
    if (bytes.length >= 6 &&
        bytes[0] == 0x47 &&
        bytes[1] == 0x49 &&
        bytes[2] == 0x46) {
      return true; // GIF
    }
    return false;
  }

  /// Downloads image bytes for Big Picture. Returns null on any failure.
  static Future<Uint8List?> _downloadNotificationImageBytes(String? url) async {
    if (url == null || url.trim().isEmpty) return null;
    HttpClient? client;
    try {
      final uri = Uri.tryParse(url.trim());
      if (uri == null || !uri.hasScheme) return null;
      client = HttpClient();
      client.connectionTimeout = const Duration(seconds: 10);
      client.idleTimeout = const Duration(seconds: 15);
      final request = await client.getUrl(uri);
      request.followRedirects = true;
      request.maxRedirects = 5;
      final response = await request.close().timeout(
        const Duration(seconds: 15),
      );
      if (response.statusCode != 200) {
        debugPrint(
          '[FCM] Promotional image HTTP ${response.statusCode}, falling back to standard notification',
        );
        return null;
      }
      final bytes = await consolidateHttpClientResponseBytes(response);
      if (!_isDecodableNotificationImage(bytes)) {
        debugPrint(
          '[FCM] Promotional image was not a valid PNG/JPEG/WEBP, falling back to standard notification',
        );
        return null;
      }
      // Downsample to max width 720px for notification tray to prevent Android Binder TransactionTooLargeException
      try {
        final codec = await instantiateImageCodec(
          Uint8List.fromList(bytes),
          targetWidth: 720,
        );
        final frameInfo = await codec.getNextFrame();
        final byteData = await frameInfo.image.toByteData(
          format: ImageByteFormat.png,
        );
        if (byteData != null) {
          return byteData.buffer.asUint8List();
        }
      } catch (resizeErr) {
        debugPrint('[FCM] Image resize notice: $resizeErr');
      }

      return Uint8List.fromList(bytes);
    } catch (e) {
      debugPrint(
        '[FCM] Promotional image download failed, falling back to standard notification: $e',
      );
    } finally {
      client?.close(force: true);
    }
    return null;
  }

  static Future<void> _showAndroidLocalFromRemoteMessage(
    RemoteMessage message,
    FlutterLocalNotificationsPlugin local,
  ) async {
    final title =
        message.notification?.title ?? message.data['title'] ?? 'QB Suite';
    final body =
        message.notification?.body ??
        message.data['body'] ??
        message.data['message'] ??
        '';
    final imageUrl = _extractImageUrl(message);
    final rawShowCta = message.data['showCta'];
    final showCta = rawShowCta == true || rawShowCta == 'true';
    final ctaText = message.data['ctaText'];
    final payload = jsonEncode(message.data);
    final notificationId = _localNotificationId(message);

    Uint8List? imageBytes;
    if (imageUrl != null) {
      imageBytes = await _downloadNotificationImageBytes(imageUrl);
    }

    Future<void> showWith({Uint8List? bytes}) {
      final androidDetails = _buildAndroidNotificationDetails(
        imageBytes: bytes,
        title: title,
        body: body,
        showCta: showCta,
        ctaText: ctaText,
      );
      return local.show(
        notificationId,
        title,
        body,
        NotificationDetails(
          android: androidDetails,
          iOS: const DarwinNotificationDetails(presentSound: true),
        ),
        payload: payload,
      );
    }

    try {
      await showWith(bytes: imageBytes);
    } catch (e) {
      debugPrint(
        '[FCM] Big Picture notification failed, retrying without image: $e',
      );
      await showWith();
    }
  }

  /// Constructs native AndroidNotificationDetails supporting BigPictureStyle and optional CTA action button
  static AndroidNotificationDetails _buildAndroidNotificationDetails({
    Uint8List? imageBytes,
    required String title,
    required String body,
    bool showCta = false,
    String? ctaText,
  }) {
    BigPictureStyleInformation? styleInformation;
    if (imageBytes != null && imageBytes.isNotEmpty) {
      styleInformation = BigPictureStyleInformation(
        ByteArrayAndroidBitmap(imageBytes),
        contentTitle: title,
        summaryText: body,
        hideExpandedLargeIcon: true,
      );
    }

    List<AndroidNotificationAction>? actions;
    if (showCta && ctaText != null && ctaText.trim().isNotEmpty) {
      actions = [
        AndroidNotificationAction(
          'cta_action',
          ctaText.trim(),
          showsUserInterface: true,
          cancelNotification: true,
        ),
      ];
    }

    return AndroidNotificationDetails(
      _androidChannel.id,
      _androidChannel.name,
      channelDescription: _androidChannel.description,
      importance: Importance.max,
      priority: Priority.max,
      icon: '@drawable/ic_notification',
      color: const Color(0xFF23C45E),
      playSound: true,
      enableVibration: true,
      visibility: NotificationVisibility.public,
      styleInformation: styleInformation,
      actions: actions,
    );
  }

  /// Initializes local notifications, channels, permissions, and FCM listeners.
  /// This method is fully idempotent and non-blocking for app startup.
  Future<void> initialize() async {
    if (_initialized || _isInitializing || kIsWeb) return;
    _isInitializing = true;

    try {
      debugPrint('[FCM] Initializing Firebase...');
      if (Firebase.apps.isEmpty) {
        await Firebase.initializeApp(
          options: DefaultFirebaseOptions.currentPlatform,
        );
      }
      debugPrint('[FCM] Firebase initialized');
    } catch (error, st) {
      debugPrint('[FCM] Firebase initialization FAILED: $error');
      debugPrintStack(stackTrace: st);
      _isInitializing = false;
      return;
    }

    const androidSettings = AndroidInitializationSettings(
      '@drawable/ic_notification',
    );
    const settings = InitializationSettings(
      android: androidSettings,
      iOS: DarwinInitializationSettings(
        requestAlertPermission: false,
        requestBadgePermission: false,
        requestSoundPermission: false,
      ),
    );
    try {
      await _local
          .initialize(
            settings,
            onDidReceiveNotificationResponse: (response) {
              _openNotificationPayload(
                response.payload,
                actionId: response.actionId,
              );
            },
          )
          .timeout(
            const Duration(seconds: 3),
            onTimeout: () {
              debugPrint('[FCM] Local notification initialization timed out');
              return false;
            },
          );

      final androidPlugin = _local
          .resolvePlatformSpecificImplementation<
            AndroidFlutterLocalNotificationsPlugin
          >();
      await androidPlugin?.createNotificationChannel(_androidChannel);
      await androidPlugin?.createNotificationChannel(_legacyChannel);

      // Android 13+ (API 33+) explicit POST_NOTIFICATIONS runtime permission prompt
      if (Platform.isAndroid) {
        final androidGranted = await androidPlugin
            ?.requestNotificationsPermission();
        debugPrint(
          '[FCM] Android POST_NOTIFICATIONS permission prompt result: $androidGranted',
        );
      }
    } catch (e) {
      debugPrint('[FCM] Local notification setup error: $e');
    }

    if (Firebase.apps.isNotEmpty) {
      try {
        final messaging = FirebaseMessaging.instance;
        // Use provisional authorization on iOS during startup to prevent modal system dialogs
        // from freezing main() before the Flutter UI mounts. Full prompt occurs in requestUINotificationPermission().
        NotificationSettings? settingsResult;
        try {
          settingsResult = await messaging
              .requestPermission(
                alert: true,
                badge: true,
                sound: true,
                provisional: true,
              )
              .timeout(const Duration(seconds: 2));
        } catch (e) {
          debugPrint('[FCM] Startup requestPermission timeout or error: $e');
        }
        final status =
            settingsResult?.authorizationStatus.name ?? 'notDetermined';
        debugPrint('[FCM] Notification permission: $status');

        // Register lifecycle observer for auto-retry on app resume
        WidgetsBinding.instance.addObserver(this);

        // Listen for FCM token refresh events
        FirebaseMessaging.instance.onTokenRefresh.listen((token) async {
          debugPrint('[FCM] FCM token refreshed: ${_maskToken(token)}');
          _cachedFcmToken = token;
          await _checkAndRegisterToken(token, force: true);
        });

        FirebaseMessaging.onMessage.listen((message) {
          debugPrint('[FCM] Foreground message received');
          _showForegroundNotification(message);
        });

        FirebaseMessaging.onMessageOpenedApp.listen((message) {
          debugPrint('[FCM] onMessageOpenedApp received');
          _handleTap(message);
        });

        try {
          final initialMessage = await FirebaseMessaging.instance
              .getInitialMessage()
              .timeout(const Duration(seconds: 2));
          if (initialMessage != null) {
            final initialKey = initialMessage.messageId ??
                initialMessage.data['notificationId']?.toString() ??
                initialMessage.data['type']?.toString() ??
                'initial_msg';
            if (!_handledInitialMessageKeys.contains(initialKey)) {
              _handledInitialMessageKeys.add(initialKey);
              debugPrint('[FCM] onMessageOpenedApp received (initialMessage)');
              _handleTap(initialMessage);
            }
          }
        } catch (e) {
          debugPrint('[FCM] getInitialMessage error: $e');
        }
      } catch (e) {
        debugPrint('[FCM] Firebase messaging setup warning: $e');
      }
    } else {
      debugPrint('[FCM] Firebase not initialized; skipping FCM message listener setup');
    }

    _initialized = true;
    _isInitializing = false;

    // Non-blocking asynchronous token fetch & registration (never blocks app startup)
    _registerCurrentTokenAsync(isStartup: true);
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) {
      final now = DateTime.now();
      if (_lastResumeRetryTime != null &&
          now.difference(_lastResumeRetryTime!).inSeconds < 30) {
        // Debounce resume retry — do not request more than once every 30 seconds
        return;
      }
      _lastResumeRetryTime = now;

      // If token generation previously failed or user is authenticated but token not registered
      if (_cachedFcmToken == null ||
          (_registeredToken == null && ApiClient().token != null)) {
        debugPrint(
          '[FCM] App resumed. Re-attempting FCM token registration...',
        );
        _registerCurrentTokenAsync(isResume: true);
      }
    }
  }

  /// Explicitly requests system notification permission (Android 13+ and iOS)
  /// when the Flutter Activity/UI is fully mounted and active.
  Future<void> requestAndroidNotificationPermission() async {
    try {
      if (Platform.isAndroid) {
        final androidPlugin = _local
            .resolvePlatformSpecificImplementation<
              AndroidFlutterLocalNotificationsPlugin
            >();
        final granted = await androidPlugin?.requestNotificationsPermission();
        debugPrint(
          '[FCM] UI-level Android POST_NOTIFICATIONS permission request: $granted',
        );

        try {
          final phStatus = await Permission.notification.request();
          debugPrint('[FCM] permission_handler notification status: $phStatus');
        } catch (phErr) {
          debugPrint('[FCM] permission_handler note: $phErr');
        }
      }

      if (Firebase.apps.isNotEmpty) {
        final settingsResult = await FirebaseMessaging.instance
            .requestPermission(
              alert: true,
              badge: true,
              sound: true,
              provisional: false,
            )
            .timeout(const Duration(seconds: 5));
        debugPrint(
          '[FCM] UI-level Firebase permission status: ${settingsResult.authorizationStatus.name}',
        );
      }
    } catch (e) {
      debugPrint('[FCM] Error requesting notification permission: $e');
    }
  }

  /// Non-blocking trigger to request and register current FCM token.
  void _registerCurrentTokenAsync({
    bool force = false,
    bool isStartup = false,
    bool isResume = false,
  }) {
    unawaited(
      _performTokenRegistration(
        force: force,
        isStartup: isStartup,
        isResume: isResume,
      ),
    );
  }

  Future<void> _performTokenRegistration({
    bool force = false,
    bool isStartup = false,
    bool isResume = false,
  }) async {
    if (_isRegisteringToken) {
      debugPrint(
        '[FCM] Token registration already in progress. Skipping duplicate request.',
      );
      return;
    }
    _isRegisteringToken = true;

    try {
      final token = await _fetchFcmTokenWithRetry();
      if (token != null && token.isNotEmpty) {
        await _checkAndRegisterToken(token, force: force);
      }
    } catch (e) {
      debugPrint('[FCM] Unexpected error during token registration flow: $e');
    } finally {
      _isRegisteringToken = false;
    }
  }

  /// Requests registration token from Firebase Messaging with safe exponential backoff
  /// for transient SERVICE_NOT_AVAILABLE and network errors.
  Future<String?> _fetchFcmTokenWithRetry({int maxAttempts = 3}) async {
    if (_cachedFcmToken != null && _cachedFcmToken!.isNotEmpty) {
      return _cachedFcmToken;
    }

    int attempt = 0;
    const delays = [
      Duration(seconds: 2),
      Duration(seconds: 5),
      Duration(seconds: 10),
    ];

    debugPrint('[FCM] Checking Google Play Services...');
    while (attempt < maxAttempts) {
      attempt++;
      try {
        debugPrint(
          '[FCM] Requesting registration token... (attempt $attempt/$maxAttempts)',
        );
        final token = await FirebaseMessaging.instance.getToken().timeout(
          const Duration(seconds: 15),
          onTimeout: () {
            throw Exception(
              'SERVICE_NOT_AVAILABLE: getToken timed out after 15s',
            );
          },
        );

        if (token != null && token.trim().isNotEmpty) {
          _cachedFcmToken = token.trim();
          _consecutiveServiceFailures = 0;
          debugPrint('[FCM] Token obtained successfully');
          debugPrint('[FCM] Token generated: YES');
          debugPrint('[FCM] FCM token: ${_maskToken(_cachedFcmToken)}');
          return _cachedFcmToken;
        } else {
          debugPrint('⚠️ [FCM] Token is null or empty');
        }
      } catch (e, stackTrace) {
        final isServiceUnavailable = _isServiceNotAvailable(e);
        final isNetwork = _isNetworkError(e);

        if (isServiceUnavailable) {
          _consecutiveServiceFailures++;
          debugPrint('[FCM] Token unavailable');
          debugPrint('[FCM] Error: SERVICE_NOT_AVAILABLE');
          if (attempt < maxAttempts) {
            final delay = delays[attempt - 1];
            debugPrint(
              '[FCM] Retrying in ${delay.inSeconds} seconds (attempt ${attempt + 1}/$maxAttempts)...',
            );
            await Future.delayed(delay);
            continue;
          } else {
            debugPrint('[FCM] Token generation failed');
            debugPrint('[FCM] Error code: SERVICE_NOT_AVAILABLE');
            if (_consecutiveServiceFailures >= 3) {
              debugPrint('[FCM] Google Play Services unavailable.');
              debugPrint(
                '[FCM] Push notifications cannot be registered on this device.',
              );
            } else {
              debugPrint('[FCM] Retry scheduled');
            }
            return null;
          }
        } else if (isNetwork) {
          debugPrint('[FCM] Token generation failed (Network error): $e');
          if (attempt < maxAttempts) {
            final delay = delays[attempt - 1];
            debugPrint('[FCM] Retrying in ${delay.inSeconds} seconds...');
            await Future.delayed(delay);
            continue;
          } else {
            debugPrint(
              '[FCM] Network unavailable for FCM. Retry scheduled on app resume.',
            );
            return null;
          }
        } else {
          debugPrint(
            '[FCM] Token generation failed with non-retryable error: $e',
          );
          debugPrintStack(stackTrace: stackTrace);
          return null;
        }
      }
    }
    return null;
  }

  bool _isServiceNotAvailable(dynamic error) {
    final str = error.toString().toUpperCase();
    return str.contains('SERVICE_NOT_AVAILABLE') ||
        str.contains('SERVICE NOT AVAILABLE') ||
        str.contains(
          'EXECUTIONEXCEPTION: JAVA.IO.IOEXCEPTION: SERVICE_NOT_AVAILABLE',
        );
  }

  bool _isNetworkError(dynamic error) {
    final str = error.toString().toUpperCase();
    return str.contains('SOCKETEXCEPTION') ||
        str.contains('TIMEOUT') ||
        str.contains('CONNECTION REFUSED') ||
        str.contains('FAILED TO CONNECT');
  }

  /// Evaluates authentication state and registers the token if authenticated,
  /// or defers registration until employee/customer login completes.
  Future<void> _checkAndRegisterToken(
    String token, {
    bool force = false,
  }) async {
    final cleanToken = token.trim();
    if (cleanToken.isEmpty) return;

    await ApiClient().ensureAuthLoaded();
    final accessToken = ApiClient().token;
    final bool hasAccessToken =
        accessToken != null &&
        accessToken.trim().isNotEmpty &&
        accessToken != 'null' &&
        accessToken != 'undefined' &&
        accessToken != '[object Object]';
    final bool isAuthenticated = hasAccessToken;

    debugPrint('🔐 [FCM] Authenticated: $isAuthenticated');
    debugPrint('🔐 [FCM] Access Token Available: $hasAccessToken');

    if (!isAuthenticated) {
      debugPrint(
        '⏳ [FCM] Registration deferred until authentication completes.',
      );
      return;
    }

    await _registerToken(cleanToken, force: force);
  }

  /// Call after authentication succeeds so the real bearer token is available
  /// to the existing /notifications/device-token endpoint.
  Future<void> registerTokenForAuthenticatedUser({bool force = false}) async {
    if (!_initialized) {
      await initialize();
      return;
    }

    if (_isRegisteringToken) {
      debugPrint(
        '[FCM] Token registration already in progress. Skipping duplicate call.',
      );
      return;
    }

    if (!force &&
        _registeredToken != null &&
        _registeredToken == _cachedFcmToken) {
      debugPrint(
        '[FCM] Token already registered with backend for this session.',
      );
      return;
    }

    _registerCurrentTokenAsync(force: force);
  }

  /// Call on logout to deactivate the FCM token on the server so the device
  /// no longer receives push notifications after sign-out.
  Future<void> unregisterToken() async {
    String? token = _registeredToken ?? _cachedFcmToken;
    if (token == null || token.trim().isEmpty) {
      _registeredToken = null;
      return;
    }

    try {
      await ApiClient().dio.delete(
        AppUrl.notificationsDeviceToken,
        data: {'token': token},
      );
      _registeredToken = null;
      debugPrint(
        '[FCM] Device token unregistered on logout (token length: ${token.length})',
      );
    } catch (error) {
      // Non-fatal: token will expire naturally or be replaced on next login.
      debugPrint('[FCM] Token unregister failed (non-fatal): $error');
    }
  }

  Future<void> _registerToken(String cleanToken, {bool force = false}) async {
    if (!force && _registeredToken == cleanToken) {
      debugPrint(
        '[FCM] Token already registered for current session (length: ${cleanToken.length})',
      );
      return;
    }

    debugPrint('📡 [FCM] Registering Token');
    debugPrint('📡 [FCM] Registration API: ${AppUrl.notificationsDeviceToken}');

    try {
      final res = await ApiClient().dio.post(
        AppUrl.notificationsDeviceToken,
        data: {
          'token': cleanToken,
          'platform': Platform.isIOS ? 'IOS' : 'ANDROID',
        },
      );
      _registeredToken = cleanToken;
      debugPrint('[FCM] Token registered with backend');
      debugPrint('[FCM] Token registered: YES');
      debugPrint('✅🔥 [FCM] TOKEN REGISTERED SUCCESSFULLY');
      debugPrint(
        '[FCM] Token registration API response: status=${res.statusCode}, success=${res.data is Map ? res.data['success'] : true}',
      );
    } on DioException catch (dioErr) {
      // If 401 Unauthorized occurs, try token refresh once
      if (dioErr.response?.statusCode == 401) {
        debugPrint(
          '🔄 [FCM] Received 401 during token registration. Attempting token refresh retry...',
        );
        try {
          final refreshedToken = await ApiClient().refreshAuthDirectly();
          if (refreshedToken != null && refreshedToken.isNotEmpty) {
            debugPrint(
              '🔄 [FCM] Access token refreshed. Retrying FCM token registration...',
            );
            final retryRes = await ApiClient().dio.post(
              AppUrl.notificationsDeviceToken,
              data: {
                'token': cleanToken,
                'platform': Platform.isIOS ? 'IOS' : 'ANDROID',
              },
            );
            _registeredToken = cleanToken;
            debugPrint('[FCM] Token registered with backend');
            debugPrint('✅🔥 [FCM] TOKEN REGISTERED SUCCESSFULLY');
            debugPrint(
              '[FCM] Token registration retry response: status=${retryRes.statusCode}',
            );
            return;
          }
        } catch (refreshErr) {
          debugPrint('❌ [FCM] Token refresh retry failed: $refreshErr');
        }
      }

      final errorMsg = dioErr.response?.data != null
          ? '${dioErr.message} - ${dioErr.response?.data}'
          : '${dioErr.message}';
      debugPrint('❌🔥 [FCM] TOKEN REGISTRATION FAILED: $errorMsg');
    } catch (error) {
      debugPrint('❌🔥 [FCM] TOKEN REGISTRATION FAILED: $error');
    }
  }

  Future<void> _showForegroundNotification(RemoteMessage message) async {
    if (await _isWelcomeAlreadyShown(message)) {
      debugPrint(
        '[FCM] Welcome notification already displayed on this device. Skipping duplicate foreground tray item.',
      );
      return;
    }

    if (await _isPlanPurchaseAlreadyShown(message)) {
      debugPrint(
        '[FCM] Plan purchase notification already displayed on this device. Skipping duplicate foreground tray item.',
      );
      return;
    }

    await _showAndroidLocalFromRemoteMessage(message, _local);
    await _markWelcomeAsShown(message);
    await _markPlanPurchaseAsShown(message);
    debugPrint('[LOCAL_NOTIFICATION] Displayed');

    final title =
        message.notification?.title ?? message.data['title'] ?? 'QB Suite';
    final body =
        message.notification?.body ??
        message.data['body'] ??
        message.data['message'] ??
        '';
    final rawShowCta = message.data['showCta'];
    final showCta = rawShowCta == true || rawShowCta == 'true';
    final ctaText = message.data['ctaText'];
    final payload = jsonEncode(message.data);

    // Customer notifications remain available through the native system tray
    // and notification history, but must never create an automatic in-app
    // SnackBar. Other app roles retain their existing foreground behavior.
    final storedRole = await SecureStorageService.getUserRole();
    if (UserRole.tryParse(storedRole) == UserRole.customer) return;

    // Respect global AppToast toggles so in-app foreground notification snackbars
    // are suppressed if toasts are disabled or restricted to auth-only across the app.
    if (!AppToast.isEnabled || AppToast.authOnly) return;

    // Suppress lead assignment notifications from in-app toast/snackBar
    final notifType = message.data['type']?.toString().toUpperCase() ?? '';
    final isLeadAssign = (notifType.contains('LEAD') && notifType.contains('ASSIGN')) ||
        (title.toLowerCase().contains('assign') &&
            (title.toLowerCase().contains('lead') || body.toLowerCase().contains('lead')));
    if (isLeadAssign) return;

    final snackBarLabel =
        (showCta && ctaText != null && ctaText.trim().isNotEmpty)
        ? ctaText.trim()
        : 'OPEN';

    messengerKey.currentState
      ?..hideCurrentSnackBar()
      ..showSnackBar(
        SnackBar(
          content: Text(body.isEmpty ? title : '$title\n$body'),
          duration: const Duration(seconds: 4),
          action: SnackBarAction(
            label: snackBarLabel,
            onPressed: () {
              messengerKey.currentState?.hideCurrentSnackBar();
              if (showCta && ctaText != null) {
                _openNotificationPayload(payload, actionId: 'cta_action');
              } else {
                _openNotificationPayload(payload);
              }
            },
          ),
        ),
      );
  }

  Future<void> _handleTap(RemoteMessage message) async {
    await _markRead(message.data['notificationId']);
    _openNotifications(
      message.data.map((key, value) => MapEntry(key, '$value')),
    );
  }

  void _openNotificationPayload(String? payload, {String? actionId}) {
    if (payload == null || payload.isEmpty) {
      _openNotifications(const {});
      return;
    }
    try {
      final decoded = jsonDecode(payload);
      final dataMap = decoded is Map
          ? decoded.map((key, value) => MapEntry('$key', '$value'))
          : const <String, String>{};

      if (actionId == 'cta_action') {
        _handleCtaAction(dataMap);
      } else {
        _openNotifications(dataMap);
      }
    } catch (error) {
      debugPrint('[FCM] Invalid local notification payload: $error');
      _openNotifications(const {});
    }
  }

  void _handleCtaAction(Map<String, String> payload) {
    debugPrint('[FCM] CTA Action tapped');
    _markRead(payload['notificationId']);

    final actionType = payload['ctaActionType'] ?? '';
    final actionValue =
        payload['ctaActionValue'] ??
        payload['deepLink'] ??
        payload['route'] ??
        '';

    _executeDestination(actionType, actionValue);
  }

  void _executeDestination(String actionType, String actionValue) {
    final trimmedVal = actionValue.trim();
    if (trimmedVal.isEmpty) {
      _openNotifications(const {});
      return;
    }

    final isWeb =
        actionType.toUpperCase() == 'WEB_URL' ||
        trimmedVal.startsWith('http://') ||
        trimmedVal.startsWith('https://');

    if (isWeb) {
      final uri = Uri.tryParse(trimmedVal);
      if (uri != null) {
        launchUrl(uri, mode: LaunchMode.externalApplication).catchError((e) {
          debugPrint('[FCM] Launch URL error: $e');
          return false;
        });
      }
      return;
    }

    // Deep link navigation
    _navigateToDeepLink(trimmedVal);
  }

  void _navigateToDeepLink(String deepLink) {
    final navigator = navigatorKey.currentState;
    if (navigator == null) return;

    var route = deepLink.trim();
    if (route.startsWith('app://')) {
      route = route.substring(6);
    }
    if (!route.startsWith('/')) {
      route = '/$route';
    }

    // Direct match against known routes or aliases
    if (route == '/plans' || route == '/customer/plans') {
      
      return;
    }
    if (route == '/orders' || route == '/customer/orders') {
      
      return;
    }
    if (route == '/leads' || route == '/employee/leads') {
      
      return;
    }
    if (route == '/work-requests' ||
        route == '/customer/work-requests' ||
        route == '/customer/work') {
      
      return;
    }

    // Attempt pushNamed, fallback to NotificationsView
    try {
      navigator.pushNamed(route);
    } catch (_) {
      navigator.push(
        MaterialPageRoute(builder: (_) => const NotificationsView()),
      );
    }
  }

  void _openNotifications(Map<String, String> payload) {
    debugPrint('[FCM] Notification opened');
    _markRead(payload['notificationId']);
    final navigator = navigatorKey.currentState;
    if (navigator == null) return;

    final leadId = payload['leadId'];
    if (leadId != null && leadId.isNotEmpty) {
      
      return;
    }

    final route = payload['route'] ?? payload['deepLink'];
    if (route != null && route.isNotEmpty) {
      _navigateToDeepLink(route);
      return;
    }

    if (payload['type'] == 'WORK_COMPLETED' || payload['type'] == 'WORK') {
      
      return;
    }

    // Default destination
    navigator.push(
      MaterialPageRoute(builder: (_) => const NotificationsView()),
    );
  }

  Future<void> _markRead(String? notificationId) async {
    if (notificationId == null || notificationId.isEmpty) return;
    try {
      await ApiClient().dio.patch(
        '${AppUrl.notifications}/$notificationId/read',
      );
    } catch (error) {
      debugPrint('[FCM] Could not mark notification read: $error');
    }
  }
